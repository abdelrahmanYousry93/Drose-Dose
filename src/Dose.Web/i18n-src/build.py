#!/usr/bin/env python3
"""Builds src/app/i18n/ar.ts and en.ts from the *.json sources here (each: {"section.key": ["ar", "en"]}).
Keeping both languages side by side makes a missing translation obvious in review."""
import json, glob, os, sys
here = os.path.dirname(os.path.abspath(__file__))
flat = {}
for f in sorted(glob.glob(os.path.join(here, '*.json'))):
    for k, v in json.load(open(f, encoding='utf-8')).items():
        if k in flat and flat[k] != v: sys.exit(f'duplicate key with different text: {k} ({f})')
        if not (isinstance(v, list) and len(v) == 2 and all(isinstance(x, str) and x for x in v)): sys.exit(f'bad entry {k} in {f}')
        flat[k] = v
def tree(i):
    root = {}
    for k, v in sorted(flat.items()):
        node = root; parts = k.split('.')
        for p in parts[:-1]:
            node = node.setdefault(p, {})
            if isinstance(node, str): sys.exit(f'key clash at {k}')
        node[parts[-1]] = v[i]
    return root
out = os.path.join(here, '..', 'src', 'app', 'i18n'); os.makedirs(out, exist_ok=True)
hdr = '// GENERATED by i18n-src/build.py from i18n-src/*.json — edit the JSON, then run: python3 i18n-src/build.py\n'
open(os.path.join(out, 'ar.ts'), 'w', encoding='utf-8').write(hdr + 'export const ar = ' + json.dumps(tree(0), ensure_ascii=False, indent=2) + ';\n')
open(os.path.join(out, 'en.ts'), 'w', encoding='utf-8').write(hdr + "import type { ar } from './ar';\n\nexport const en: typeof ar = " + json.dumps(tree(1), ensure_ascii=False, indent=2) + ';\n')
print(f'{len(flat)} keys')
